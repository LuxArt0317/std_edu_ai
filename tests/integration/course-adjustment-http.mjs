async function get(query,token,status=200){
  const headers=token?{authorization:'Bearer '+token}:{};
  if(revision){
    const response=await fetch(site+'/api/affairs-data?'+new URLSearchParams(query),{headers,signal:AbortSignal.timeout(12000),redirect:'error'});
    assert.equal(response.status,status);
    return response.json();
  }
  let code,result;
  const response={status(value){code=value;return response;},json(value){result=value;},setHeader(){}};
  await handler({method:'GET',query,headers},response);
  assert.equal(code,status);
  return result;
}
