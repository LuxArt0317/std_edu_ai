  expect(visible.data.owner_id).toBe(state.users.owner.id)
  await page.reload()
  const request = page.locator('.student-support-center [data-slot="card"]').filter({ hasText: state.marker+' Student handoff' })
  await expect(request).toContainText('in progress')
