async function login(page: Page, role: string) {
  const session = role === 'owner' ? (await (await roleClient(role)).auth.getSession()).data.session : state.users[role].session
  if (!session) throw new Error('A verified browser session is required.')
  await page.addInitScript(session => localStorage.setItem('stu-nexus-auth', JSON.stringify(session)), session)
  await page.goto('/app')
  await expect(page.locator('.school-content')).toBeVisible({ timeout: 45000 })
}
async function roleClient(role: string) { return clientForRole(state, role) }
for (const role of ['owner','admin','president','vice_president','dean','registrar','department_head','faculty','advisor','admissions','finance','support','librarian','student']) {
  test(`${role} authenticates and opens every authorized workspace`, async ({ page }) => {
    if (role === 'owner') test.setTimeout(180000)
    const errors: string[] = []
    page.on('console', message => { if (message.type() === 'error' && message.text().includes('STU_NEXUS_RENDER_FAILURE')) errors.push('Caught application rendering error') })
    page.on('pageerror', error => errors.push(error.message))
    await login(page, role)
    const nav = page.getByRole('navigation', { name: 'School navigation' })
    const labels = await nav.getByRole('button').allTextContents()
    expect(labels.length).toBeGreaterThanOrEqual(4)
    for (const label of labels) {
      await nav.getByRole('button').filter({ hasText: label }).click()
      await expect(page.locator('.school-content')).toBeVisible()
      if (/Tasks|Students|Alerts|Admissions|Cases|Messages|Knowledge|Reports/.test(label)) await expect(page.locator('.nexus-page-heading')).toBeVisible()
      await expect(page.locator('.school-content')).not.toContainText('Unable to load')
      await expect(page.getByRole('button', { name: 'Back to School OS' })).toHaveCount(0)
      await expect(page.getByRole('navigation', { name: 'CRM navigation' })).toHaveCount(0)
      if (role === 'owner') {
        await page.waitForFunction(() => document.getAnimations().filter(animation => animation.playState === 'running' && animation.effect?.getTiming().iterations !== Infinity).length === 0)
        const scan = await new AxeBuilder({ page }).withTags(['wcag2a','wcag2aa','wcag21a','wcag21aa']).analyze()
        expect(scan.violations.filter(item => item.impact === 'serious' || item.impact === 'critical').map(item => ({ label, id: item.id, nodes: item.nodes.map(node => node.target) }))).toEqual([])
      }
    }
    if (role === 'student') await expect(nav.getByRole('button', { name: /Academics|People|Cases|Tasks|Admissions|Messages/ })).toHaveCount(0)
    expect(errors).toEqual([])
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  })
}
test('curriculum RPC enforces assignment, independent review, status transitions and audit', async () => {
  const faculty = await roleClient('faculty'), student = await roleClient('student'), owner = await roleClient('owner'), support = await roleClient('support')
  const args = { p_action: 'create', p_section_id: state.ids.section, p_summary: `${state.marker} Review subject sequence`, p_details: 'The assigned course requires a revised prerequisite sequence based on learner readiness.' }
  expect((await student.rpc('manage_curriculum_change_request', args)).error).toBeTruthy()
  expect((await support.rpc('manage_curriculum_change_request', args)).error).toBeTruthy()
  const created = await faculty.rpc('manage_curriculum_change_request', args)
  expect(created.error).toBeNull()
  const id = created.data.id
  expect(created.data.status).toBe('submitted')
  const reviewerNotice = await owner.from('notifications').select('id').eq('action_url', '/crm?curriculum_request='+id)
  expect(reviewerNotice.error).toBeNull()
  expect(reviewerNotice.data.length).toBeGreaterThan(0)
  expect((await faculty.rpc('manage_curriculum_change_request', { p_action: 'review', p_request_id: id, p_decision: 'approved', p_reason: 'Attempted self review denied' })).error).toBeTruthy()
  expect((await student.from('curriculum_change_requests').select('id').eq('id', id)).data).toEqual([])
  expect((await faculty.from('curriculum_change_requests').update({ status: 'approved' }).eq('id', id)).error).toBeTruthy()
  expect((await faculty.rpc('manage_curriculum_change_request', { p_action: 'edit', p_request_id: id, p_summary: args.p_summary+' revised', p_details: args.p_details })).error).toBeNull()
  expect((await owner.rpc('manage_curriculum_change_request', { p_action: 'review', p_request_id: id, p_decision: null, p_reason: 'Invalid decision rejected' })).error).toBeTruthy()
  const reviewed = await owner.rpc('manage_curriculum_change_request', { p_action: 'review', p_request_id: id, p_decision: 'approved', p_reason: 'Verified academic sequence meets the institutional requirements.' })
  expect(reviewed.error).toBeNull()
  expect(reviewed.data.reviewed_by).toBe(state.users.owner.id)
  const teacherNotice = await faculty.from('notifications').select('title').eq('action_url', '/crm?curriculum_request='+id).eq('kind','curriculum_decision').single()
  expect(teacherNotice.error).toBeNull()
  expect(teacherNotice.data.title).toContain('approved')
  expect((await faculty.rpc('manage_curriculum_change_request', { p_action: 'withdraw', p_request_id: id, p_reason: 'Cannot change reviewed proposal' })).error).toBeTruthy()
  const plan = await admin.from('curriculum_plans').select('status,source_payload').eq('id', state.ids.plan).single()
  expect(plan.data.status).toBe('draft')
  expect(plan.data.source_payload.subjects).toHaveLength(1)
  const audit = await admin.from('controlled_action_audit').select('action,actor_id,before_state').eq('entity_type','curriculum_change_request').eq('entity_id', id)
  expect(audit.error).toBeNull()
  expect(audit.data).toHaveLength(3)
  expect(audit.data.every((row: any) => row.actor_id && row.before_state)).toBe(true)
})
