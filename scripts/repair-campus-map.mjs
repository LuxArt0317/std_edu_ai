/** Restore only the publisher's missing map image; retain the captured layout. */
import fs from 'node:fs/promises';import {createHash} from 'node:crypto';
import {downloadSchoolAsset} from './lib/download-school-asset.mjs';
const read=async name=>JSON.parse(await fs.readFile('src/features/public/mirror/'+name+'.json','utf8'));
const warnings=await read('import-warnings'),assets=await read('assets');
const pageSource='https://www.oica.stu.edu.tw/en/school-map/';
const source=warnings.find(row=>row.page===pageSource&&row.reason==='media_missing')?.source||assets.find(row=>row.source.includes('/sites/27/2020/06/map1_'))?.source;
if(!source)throw Error('Original map image is not registered');
const previous=assets.find(row=>row.source===source);
let buffer=previous?await fs.readFile('public'+previous.file).catch(()=>null):null;
if(!buffer||createHash('sha256').update(buffer).digest('hex')!==previous.checksum)buffer=(await downloadSchoolAsset(source)).buffer;
if(buffer.subarray(0,8).toString('hex')!=='89504e470d0a1a0a'||buffer.readUInt32BE(16)!==768||buffer.readUInt32BE(20)!==840)throw Error('Unexpected campus-map PNG');
const file='/school-assets/'+createHash('sha256').update(source).digest('hex').slice(0,20)+'.png';
const pages=await read('pages'),page=pages.find(row=>row.source===pageSource);
if(!page)throw Error('School Map page is not registered');
const html=await fs.readFile('public'+page.file,'utf8');
if(createHash('sha256').update(html).digest('hex')!==page.checksum)throw Error('Map capture changed; refusing to overwrite');
const tags=html.match(/<img\b(?=[^>]*\bwp-image-2025\b)[^>]*>/gu)||[];
if(tags.length!==1)throw Error('Map image element is ambiguous');
const tag=tags[0].replace(/\bsrc="[^"]*"/u,'src="'+file+'"').replace(/\balt="[^"]*"/u,'alt="Shu-Te University campus map"');
const repaired=html.replace(tags[0],tag),checksum=createHash('sha256').update(buffer).digest('hex');
page.preRepairChecksum ||= page.checksum;page.checksum=createHash('sha256').update(repaired).digest('hex');
const nextAssets=await read('assets');
if(!nextAssets.some(row=>row.source===source))nextAssets.push({source,file,checksum,sourceChecksum:checksum,bytes:buffer.length});
const nextWarnings=(await read('import-warnings')).filter(row=>!(row.source===source&&row.page===pageSource&&row.reason==='media_missing'));
const write=async(path,value)=>{await fs.writeFile(path+'.tmp',value);await fs.rename(path+'.tmp',path)};
await write('public'+file,buffer);await write('public'+page.file,repaired);
await write('src/features/public/mirror/pages.json',JSON.stringify(pages,null,2)+'\n');
await write('src/features/public/mirror/assets.json',JSON.stringify(nextAssets,null,2)+'\n');
await write('src/features/public/mirror/import-warnings.json',JSON.stringify(nextWarnings,null,2)+'\n');
console.log(JSON.stringify({restored:file,bytes:buffer.length,page:page.route}));
